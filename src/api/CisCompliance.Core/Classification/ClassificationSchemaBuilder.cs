using System.Text.Json.Nodes;

namespace CisCompliance.Core.Classification;

// Ported from build_response_schema() in classify.py.
//
// Property order below is not cosmetic: the model fills in a JSON object's
// fields in the order the schema declares them, left to right, token by
// token, and it never revises an earlier field once later ones are written.
// "reasoning" is placed before "label"/"rule_ids" so the override analysis
// actually happens before the decision is committed to, not after. An
// earlier version of this schema (in the Python original) had "label"
// first, and the model would sometimes write a "reasoning" string that
// correctly worked out a mixed-contract override applied, while "label"
// (already generated by that point) still said Services, the analysis was
// real but too late to change anything. Putting reasoning first makes it
// load-bearing instead of decorative.
//
// Built with JsonObject and ordered object-initializer syntax rather than
// serializing a POCO/record, because JsonObject preserves insertion order as
// a documented guarantee, whereas reflection-based member order on a
// serialized type is an implementation detail, not a contract. See
// ClassificationSchemaBuilderTests for the test that guards this ordering.
public static class ClassificationSchemaBuilder
{
    public const string SchemaName = "cis_line_item_classification";

    public static string Build(IReadOnlyList<string> ruleIds)
    {
        var schema = new JsonObject
        {
            ["type"] = "object",
            ["properties"] = new JsonObject
            {
                ["line_items"] = new JsonObject
                {
                    ["type"] = "array",
                    ["items"] = BuildLineItemSchema(ruleIds),
                },
            },
            ["required"] = new JsonArray("line_items"),
            ["additionalProperties"] = false,
        };

        return schema.ToJsonString();
    }

    private static JsonObject BuildLineItemSchema(IReadOnlyList<string> ruleIds) =>
        new()
        {
            ["type"] = "object",
            ["properties"] = new JsonObject
            {
                // Order is load bearing, see the class comment above.
                ["line_id"] = new JsonObject { ["type"] = "string" },
                ["reasoning"] = new JsonObject { ["type"] = "string" },
                ["rule_ids"] = new JsonObject
                {
                    ["type"] = "array",
                    ["items"] = new JsonObject
                    {
                        ["type"] = "string",
                        ["enum"] = new JsonArray(ruleIds.Select(id => JsonValue.Create(id)).ToArray()),
                    },
                },
                ["confidence"] = new JsonObject { ["type"] = "string", ["enum"] = new JsonArray("high", "low") },
                ["label"] = new JsonObject { ["type"] = "string", ["enum"] = new JsonArray("Construction", "Services") },
            },
            ["required"] = new JsonArray("line_id", "reasoning", "rule_ids", "confidence", "label"),
            ["additionalProperties"] = false,
        };
}
